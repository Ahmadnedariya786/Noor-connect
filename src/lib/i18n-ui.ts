/**
 * Returns complete UI strings dictionary for a given language code.
 * Falls back safely to English if language code is not recognized.
 */
export function getAppUIStrings(lang: LanguageCode | string = 'en'): AppUIStrings {
  const code = (lang || 'en').toLowerCase().slice(0, 2) as LanguageCode;
  const dict = UI_DICTIONARIES[code] || UI_DICTIONARIES.en;
  return {
    ...dict,
    remainingSuffix:
      code === 'ar' ? 'متبقي' :
      code === 'ur' ? 'باقی' :
      code === 'gu' ? 'બાકી' :
      code === 'hi' ? 'शेष' :
      code === 'bn' ? 'বাকি' :
      code === 'ru' ? 'осталось' :
      code === 'fr' ? 'restant' : 'remaining',
    afterPrefix:
      code === 'ar' ? 'بعد' :
      code === 'ur' ? 'بعد' :
      code === 'gu' ? 'પછી' :
      code === 'hi' ? 'के बाद' :
      code === 'bn' ? 'পরে' :
      code === 'ru' ? 'После' :
      code === 'fr' ? 'Après' : 'After',
    shareOrPrint: dict.monthlyTimetableSub || 'Share image or print A4 PDF',
  };
}
